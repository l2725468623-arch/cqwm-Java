CREATE TABLE IF NOT EXISTS employee (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(32), username VARCHAR(32) UNIQUE, password VARCHAR(64),
  phone VARCHAR(11), sex VARCHAR(2), id_number VARCHAR(18), status INT,
  create_time TIMESTAMP, update_time TIMESTAMP, create_user BIGINT, update_user BIGINT
);
CREATE TABLE IF NOT EXISTS category (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,type INT,name VARCHAR(32) UNIQUE,sort INT,status INT,
  create_time TIMESTAMP,update_time TIMESTAMP,create_user BIGINT,update_user BIGINT
);
CREATE TABLE IF NOT EXISTS dish (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,name VARCHAR(32) UNIQUE,category_id BIGINT,price DECIMAL(10,2),
 image VARCHAR(255),description VARCHAR(255),status INT,create_time TIMESTAMP,update_time TIMESTAMP,create_user BIGINT,update_user BIGINT
);
CREATE TABLE IF NOT EXISTS dish_flavor (id BIGINT AUTO_INCREMENT PRIMARY KEY,dish_id BIGINT,name VARCHAR(32),`value` VARCHAR(255));
CREATE TABLE IF NOT EXISTS setmeal_dish (id BIGINT AUTO_INCREMENT PRIMARY KEY,setmeal_id BIGINT,dish_id BIGINT,name VARCHAR(32),price DECIMAL(10,2),copies INT);
CREATE TABLE IF NOT EXISTS setmeal (id BIGINT PRIMARY KEY, category_id BIGINT);
CREATE TABLE IF NOT EXISTS orders (id BIGINT PRIMARY KEY);
